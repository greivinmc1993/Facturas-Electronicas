'use strict';
const assert=require('node:assert/strict');
const {compatibleNode,cryptoSelfTest,diagnoseXadesEngine,REQUIRED}=require('../electron/fe-xades-engine-readiness.cjs');
(async()=>{
 let tests=0;
 const check=(fn)=>{fn();tests++};
 check(()=>assert.equal(compatibleNode('20.19.0'),true));
 check(()=>assert.equal(compatibleNode('20.18.9'),false));
 check(()=>assert.equal(compatibleNode('22.11.9'),false));
 check(()=>assert.equal(compatibleNode('22.12.0'),true));
 check(()=>assert.equal(compatibleNode('22.16.0'),true));
 check(()=>assert.equal(compatibleNode('19.99.0'),false));
 check(()=>assert.equal(compatibleNode('desconocido'),false));
 check(()=>assert.deepEqual(REQUIRED,['xadesjs','xmldsigjs','xml-core']));
 const cryptoOk=await cryptoSelfTest();assert.equal(cryptoOk,true);tests++;
 const missing=await diagnoseXadesEngine({nodeVersion:'22.12.0',resolvePackage:()=>{throw Error('ausente')}});
 check(()=>assert.equal(missing.nodeCompatible,true));
 check(()=>assert.equal(missing.cryptoOk,true));
 check(()=>assert.equal(missing.specializedEngineInstalled,false));
 check(()=>assert.equal(missing.specializedEngineValidated,false));
 check(()=>assert.equal(missing.canSignFiscalXml,false));
 check(()=>assert.equal(missing.canIssue,false));
 check(()=>assert.equal(missing.canSend,false));
 const mocked=await diagnoseXadesEngine({resolvePackage:n=>'/mock/'+n});
 check(()=>assert.equal(mocked.specializedEngineInstalled,true));
 check(()=>assert.equal(mocked.specializedEngineValidated,false));
 check(()=>assert.equal(mocked.canIssue,false));
 check(()=>assert.equal(mocked.usesRealCertificate,false));
 const old=await diagnoseXadesEngine({nodeVersion:'18.0.0',resolvePackage:()=>{throw Error('ausente')}});
 check(()=>assert.equal(old.nodeCompatible,false));
 console.log(`QA v0.6.83 compatibilidad de firma: ${tests}/${tests} aprobadas`);
})().catch(e=>{console.error(e);process.exitCode=1});
